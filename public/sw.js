// ─────────────────────────────────────────────────────────────────────────────
// 리디브 서비스 워커 (2026-11-28)
//   · 홈 화면에 추가(설치) 요건 중 하나인 fetch 핸들러만 갖는다.
//   · **아무것도 캐시하지 않는다** — 구역 경계(zones.geojson)·경매·실거래는 배포마다
//     통째로 바뀌므로, 서비스 워커가 옛 파일을 물고 있으면 지도에 지난 배포의 경계가
//     그대로 남는다(2026-11-17 제보). 그래서 respondWith 없이 브라우저 기본 동작에 맡긴다.
//   · 새 배포가 올라오면 곧바로 새 워커로 교체한다.
// ─────────────────────────────────────────────────────────────────────────────
self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

// 캐시 없음 — 요청은 항상 네트워크로 그대로 흐른다.
self.addEventListener("fetch", () => {});

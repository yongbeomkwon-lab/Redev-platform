//     (서울특별시고시 제2006-357호). 이 구역 레코드의 rightsNote 에 이미 적혀 있는 값이다.
//     지구 단위 레코드라 구역별(한남2~5구역) 단계 날짜는 각 구역 레코드에 따로 들어 있다.
//
// 권리산정기준일은 여기서 건드리지 않는다 — 6곳 모두 정본에 이미 값이 있고
// (한남재정비촉진지구·북아현1-1·신림1·노량진1 = 2003-12-30, 반포주공1단지 3주구 2016-09-13,
//  성수전략정비지구2 2009-04-23), 그 값이 화면에 그대로 나온다.
// ─────────────────────────────────────────────────────────────────────────────


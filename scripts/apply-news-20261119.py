def circle_ring(lat: float, lng: float, radius_m: float, points: int = 96):
    ring = []
    for i in range(points):
        t = 2 * math.pi * i / points
        ring.append(
            [round(lng + radius_m * math.cos(t) / M_LNG, 7), round(lat + radius_m * math.sin(t) / M_LAT, 7)]
        )
    ring.append(ring[0][:])
    return ring


def find(features, zone_id):
    for f in features:
        if f["properties"].get("id") == zone_id:
            return f
    return None


def upsert(features, props, geometry):
    """같은 id 가 있으면 속성만 갱신, 없으면 추가. 추가했으면 True."""
    feat = find(features, props["id"])
    if feat is None:
        features.append({"type": "Feature", "id": props["id"], "properties": props, "geometry": geometry})
        return True
    feat["properties"].update(props)
    feat["geometry"] = geometry
    return False



def measured_area() -> float:
    lat = sum(p[0] for p in RING) / len(RING)
    x = [p[1] * 111320 * math.cos(math.radians(lat)) for p in RING]
    y = [p[0] * 110540 for p in RING]
    s = 0.0
    for i in range(len(RING)):
        j = (i + 1) % len(RING)
        s += x[i] * y[j] - x[j] * y[i]
    return abs(s) / 2


def apply() -> int:
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    entry = next((z for z in src if z.get("id") == ZONE_ID), None)
    if entry is None:
        print("[실패] seoul-zones.json에 구역 없음:", ZONE_ID)
        return 1
    entry.update(PROPS)
    entry["sid"] = PROPS["sourceId"]
    entry["polygon"] = RING
    entry.pop("parts", None)
    entry.pop("holes", None)
    SOURCE.write_text(json.dumps(src, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"[저장] {ZONE_ID} — {len(RING)}정점, 고시면적 {PROPS['area']:,.1f}㎡, 계측 {measured_area():,.1f}㎡")
    return 0



def check() -> int:
    bad = 0
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    feat = next((f for f in geo["features"] if f["properties"].get("id") == ZONE_ID), None)
    if not feat:
        print("[실패] geojson에 구역 없음:", ZONE_ID)
        return 1
    geom = feat.get("geometry")
    ok = (
        geom
        and geom.get("type") == "Polygon"
        and feat["properties"].get("geom") == PROPS["geom"]
        and len(geom["coordinates"][0]) == len(POLYGON_LATLNG) + 1
    )
    print(f"[{ 'OK' if ok else 'FAIL' }] geojson geometry={geom and geom.get('type')} "
          f"geom={feat['properties'].get('geom')} name={feat['properties'].get('name')}")
    if not ok:
        bad += 1
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    entry = next((z for z in src if z.get("id") == ZONE_ID), None)
    ok2 = entry and entry.get("polygon") and len(entry["polygon"]) == len(POLYGON_LATLNG) and entry.get("geom") == PROPS["geom"]
    print(f"[{ 'OK' if ok2 else 'FAIL' }] seoul-zones.json polygon={bool(entry and entry.get('polygon'))} geom={entry.get('geom') if entry else None}")
    if not ok2:
        bad += 1
    return bad


def apply() -> int:
    # 1) public/data/zones.geojson — 배포 산출물
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    feat = next((f for f in geo["features"] if f["properties"].get("id") == ZONE_ID), None)
    if not feat:
        print("[실패] geojson에 구역 없음:", ZONE_ID)
        return 1
    props = feat["properties"]
    props.pop("centerLabel", None)
    props.update({k: v for k, v in PROPS.items()})
    ring = [[lng, lat] for lat, lng in POLYGON_LATLNG]
    ring.append(ring[0])
    feat["geometry"] = {"type": "Polygon", "coordinates": [ring]}
    GEOJSON.write_text(json.dumps(geo, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("[geojson] noryangjin-14 갱신 —", len(ring) - 1, "정점")

    # 2) src/data/seoul-zones.json — 파이프라인 원천
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    entry = next((z for z in src if z.get("id") == ZONE_ID), None)
    if entry is None:
        print("[경고] seoul-zones.json에 구역 없음 — 원천은 건너뜀")
        return 0
    entry.pop("centerLabel", None)
    for k, v in PROPS.items():
        entry[k] = v
    entry["sid"] = PROPS["sourceId"]
    entry["polygon"] = POLYGON_LATLNG
    entry.pop("parts", None)
    SOURCE.write_text(json.dumps(src, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("[seoul-zones] noryangjin-14 갱신 —", len(POLYGON_LATLNG), "정점")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv else apply())

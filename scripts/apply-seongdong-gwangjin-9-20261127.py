def apply():
    zones = json.loads(SOURCE.read_text(encoding="utf-8"))
    before = {z["id"]: json.dumps(z, ensure_ascii=False, sort_keys=True) for z in zones}
    before_count = len(zones)

    update_geumho_1458(zones)
    update_geumho21(zones)
    update_yongdap1(zones)
    update_yongdap2(zones)

    existing = {z["id"] for z in zones}
    added = []
    for spec in NEW_ZONES:
        if spec["id"] in existing:
            continue
        rec = dict(spec)
        rec.setdefault("featured", False)
        zones.append(rec)
        added.append(spec["id"])

    SOURCE.write_text(json.dumps(zones, ensure_ascii=False), encoding="utf-8")

    node = shutil.which("node") or "node"
    for cmd in ([node, "scripts/export-geojson.mjs"], [node, "scripts/build-zone-index.mjs"]):
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        print("$", " ".join(cmd), "→", r.returncode)
        if r.returncode != 0:
            print(r.stdout[-3000:])
            print(r.stderr[-3000:])
            raise SystemExit("!! 재생성 실패")

    meta = json.loads(META.read_text(encoding="utf-8"))
    meta[META_KEY] = {
        "asOf": AS_OF,
        "note": (
            "성동·광진 9곳 — 금호동4가 1458 유형·단계 정정(지주택·건축심의통과), 금호21 시공사선정(2026-02-07), "
            "금남시장·금호현대·응봉대림1차·마장동 793-22 신규 등록, 용답1·2 표기·면적·권리산정기준일 갱신"
        ),
        "zones": {
            zid: {"new": zid in added}
            for zid in [
                "11000UQ120PS202505310983",
                "11000UQ120PS202411014498",
                "sd-geumnam-market",
                "sd-eungbong-geumho-hyundai",
                "sd-eungbong-daerim1",
                "sd-majang-793-22",
                "sy-yongdap1",
                "yongdap-2",
            ]
        },
    }
    META.write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")

    # 기존 구역이 조용히 바뀌지 않았는지
    now = json.loads(SOURCE.read_text(encoding="utf-8"))
    changed = [
        z["id"] for z in now
        if z["id"] in before
        and z["id"] not in {
            "11000UQ120PS202505310983", "11000UQ120PS202411014498", "sy-yongdap1", "yongdap-2"
        }
        and json.dumps(z, ensure_ascii=False, sort_keys=True) != before[z["id"]]
    ]
    print(f"구역 {before_count} → {len(now)} (+{len(added)}: {', '.join(added)})")
    print("의도치 않게 바뀐 구역:", changed or "없음")
    if changed:
        raise SystemExit("!! 다른 구역이 바뀌었습니다")

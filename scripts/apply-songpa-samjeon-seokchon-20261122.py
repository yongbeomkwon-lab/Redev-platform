def _center(ring):
    lat = sum(p[0] for p in ring[:-1]) / (len(ring) - 1)
    lng = sum(p[1] for p in ring[:-1]) / (len(ring) - 1)
    return [round(lat, 6), round(lng, 6)]


def _ring_closed(ring):
    r = [[round(p[0], 6), round(p[1], 6)] for p in ring]
    if r[0] != r[-1]:
        r.append(r[0][:])
    return r


def _props(z):
    ring = _ring_closed(z["ring"])
    return {
        "id": z["id"],
        "name": z["name"],
        "alias": z["alias"],
        "type": TYPE,
        "kind": KIND,
        "stage": STAGE,
        "gu": GU,
        "area": z["area"],
        "households": z["households"],
        "featured": False,
        "sourceId": "재개발닷컴·정비닥터 구역정보(면적·소유자·노후도) + 연합뉴스·한국경제·스마트투데이 보도(2026)",
        "geom": "필지정합",
        "boundaryApprox": False,
        "centerLabel": z["centerLabel"],
        "center": _center(ring),
        "note": z["note"],
        "areaNote": z["areaNote"],
        "boundaryNote": z["boundaryNote"],
        "sources": z["sources"],
        "asOf": AS_OF,
    }


def _feature(z):
    ring = _ring_closed(z["ring"])
    return {
        "type": "Feature",
        "id": z["id"],
        "properties": _props(z),
        "geometry": {"type": "Polygon", "coordinates": [[[p[1], p[0]] for p in ring]]},
    }


def check() -> int:
    bad = 0
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    feats = geo["features"]
    ids = [f["properties"].get("id") for f in feats]
    dup = {i for i in ids if ids.count(i) > 1}
    print(f"[{'OK' if not dup else 'FAIL'}] 중복 id 없음 (features={len(feats)}, dup={sorted(dup)})")
    bad += 0 if not dup else 1

    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    for z in ZONES:
        feat = next((f for f in feats if f["properties"].get("id") == z["id"]), None)
        if not feat:
            print(f"[FAIL] geojson에 구역 없음: {z['id']}")
            bad += 1
            continue
        ring = _ring_closed(z["ring"])
        coords = feat["geometry"]["coordinates"][0]
        geom_ok = (
            feat["geometry"]["type"] == "Polygon"
            and len(coords) == len(ring)
            and all(abs(c[0] - p[1]) < 1e-9 and abs(c[1] - p[0]) < 1e-9 for c, p in zip(coords, ring))
        )
        p = feat["properties"]
        prop_ok = (
            p.get("geom") == "필지정합"
            and p.get("boundaryApprox") is False
            and p.get("type") == TYPE
            and p.get("stage") == STAGE
            and p.get("area") == z["area"]
            and p.get("name") == z["name"]
            and p.get("asOf") == AS_OF
        )
        print(
            f"[{'OK' if geom_ok and prop_ok else 'FAIL'}] geojson {z['name']} ({z['id']}) "
            f"verts={len(coords)} geom={p.get('geom')} approx={p.get('boundaryApprox')} "
            f"area={p.get('area')} center={p.get('center')}"
        )
        bad += 0 if geom_ok and prop_ok else 1

        entry = next((e for e in src if e.get("id") == z["id"]), None)
        ok2 = (
            entry is not None
            and entry.get("geom") == "필지정합"
            and entry.get("boundaryApprox") is False
            and len(entry.get("polygon") or []) == len(ring) - 1
            and entry.get("area") == z["area"]
            and entry.get("stage") == STAGE
        )
        print(
            f"[{'OK' if ok2 else 'FAIL'}] seoul-zones {z['id']} "
            f"polygon={len(entry.get('polygon') or []) if entry else 0} "
            f"geom={entry.get('geom') if entry else None} area={entry.get('area') if entry else None}"
        )
        bad += 0 if ok2 else 1

    meta = geo.get("metadata", {})
    ok3 = meta.get(META_KEY) is not None and meta.get("count") == len(feats)
    print(
        f"[{'OK' if ok3 else 'FAIL'}] metadata.count={meta.get('count')} features={len(feats)} "
        f"batch={META_KEY in meta}"
    )
    bad += 0 if ok3 else 1

    if META_PATH.exists():
        smeta = json.loads(META_PATH.read_text(encoding="utf-8"))
        ok3b = FIX_META_KEY in meta and FIX_META_KEY in smeta
        print(f"[{'OK' if ok3b else 'FAIL'}] zones-meta·geojson 배치 기록 {FIX_META_KEY}")
        bad += 0 if ok3b else 1

    # 겹침 검사(선택) — shapely/pyproj 가 있으면 m² 단위로 확인한다.
    try:
        from shapely.geometry import shape
        from shapely.ops import transform as shp_transform, unary_union
        import pyproj

        proj = pyproj.Transformer.from_crs(4326, 5179, always_xy=True)

        def to_m(g):
            return shp_transform(lambda x, y, z=None: proj.transform(x, y), g)

        new = {f["properties"]["id"]: to_m(shape(f["geometry"])) for f in feats if f["properties"].get("id") in {z["id"] for z in ZONES}}
        others = [to_m(shape(f["geometry"])) for f in feats if f["properties"].get("id") not in new and f.get("geometry")]
        ov_other = 0.0
        for g in new.values():
            for o in others:
                if g.bounds[0] > o.bounds[2] or g.bounds[2] < o.bounds[0]:
                    continue
                ov_other += g.intersection(o).area
        keys = list(new)
        ov_self = 0.0
        for i in range(len(keys)):
            for j in range(i + 1, len(keys)):
                ov_self += new[keys[i]].intersection(new[keys[j]]).area
        ok4 = ov_other < 1 and ov_self < 1
        print(f"[{'OK' if ok4 else 'FAIL'}] 기존 구역 겹침 {ov_other:.2f}㎡ · 새 구역끼리 겹침 {ov_self:.2f}㎡")
        for k, g in new.items():
            print(f"       {k}: 계측 {g.area:,.0f}㎡")
        bad += 0 if ok4 else 1
    except Exception as exc:  # pragma: no cover
        print(f"[SKIP] 겹침 검사(라이브러리 없음: {exc})")

    print(f"→ 총 구역 수 {len(feats)}곳")
    return bad


def apply() -> int:
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    feats = geo["features"]
    for z in ZONES:
        feat = _feature(z)
        cur = next((f for f in feats if f["properties"].get("id") == z["id"]), None)
        if cur is None:
            feats.append(feat)
            print(f"[geojson] 새 구역 추가: {z['name']} ({z['id']})")
        else:
            cur["properties"] = feat["properties"]
            cur["geometry"] = feat["geometry"]
            print(f"[geojson] 기존 구역 갱신: {z['name']} ({z['id']})")
        print(f"          면적(공개) {z['area']:,}㎡ · 정점 {len(_ring_closed(z['ring'])) - 1} · 중심 {feat['properties']['center']}")
    geo.setdefault("metadata", {})[META_KEY] = META
    geo["metadata"][FIX_META_KEY] = FIX_META
    geo["metadata"]["count"] = len(feats)
    GEOJSON.write_text(json.dumps(geo, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"[geojson] features={len(feats)}")

    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    for z in ZONES:
        props = _props(z)
        entry = next((e for e in src if e.get("id") == z["id"]), None)
        if entry is None:
            entry = {"id": z["id"]}
            src.append(entry)
            print(f"[seoul-zones] 새 구역 추가: {z['id']}")
        else:
            print(f"[seoul-zones] 기존 구역 갱신: {z['id']}")
        entry.update(props)
        entry["sid"] = props["sourceId"]
        # 폐합 없이 [lat, lng] 링만 저장한다(내보내기 스크립트가 폐합한다)
        entry["polygon"] = [[p[0], p[1]] for p in _ring_closed(z["ring"])][:-1]
    SOURCE.write_text(json.dumps(src, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"[seoul-zones] 구역={len(src)}")

    smeta = json.loads(META_PATH.read_text(encoding="utf-8"))
    smeta[FIX_META_KEY] = FIX_META
    META_PATH.write_text(json.dumps(smeta, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"[zones-meta] 배치 기록 추가: {FIX_META_KEY}")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv else apply())

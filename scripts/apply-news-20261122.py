def _entry(items: list[dict], zone_id: str) -> dict | None:
    return next((z for z in items if z.get("id") == zone_id), None)


def check() -> int:
    bad = 0
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    for zid, props in TARGETS.items():
        feat = next((f for f in geo["features"] if f["properties"].get("id") == zid), None)
        p = (feat or {}).get("properties", {})
        ok = (
            bool(feat)
            and p.get("stage") == props["stage"]
            and abs((p.get("area") or 0) - props["area"]) < 0.05
            and (p.get("alias") or [])[:2] == props["alias"][:2]
            and (props.get("geom") is None or p.get("geom") == props.get("geom"))
            and len(p.get("sources") or []) >= len(props["sources"])
            and p.get("asOf") == props["asOf"]
        )
        print(f"[{'OK' if ok else 'FAIL'}] geojson {zid} {p.get('name')} stage={p.get('stage')} area={p.get('area')} type={p.get('type')}")
        bad += 0 if ok else 1
        e = _entry(src, zid) or {}
        ok2 = (
            e.get("stage") == props["stage"]
            and abs((e.get("area") or 0) - props["area"]) < 0.05
            and (e.get("alias") or [])[:2] == props["alias"][:2]
        )
        print(f"[{'OK' if ok2 else 'FAIL'}] seoul-zones {zid} stage={e.get('stage')} area={e.get('area')}")
        bad += 0 if ok2 else 1
    ok3 = geo["metadata"].get(META_KEY) is not None
    print(f"[{'OK' if ok3 else 'FAIL'}] metadata batch={META_KEY in geo['metadata']} count={geo['metadata'].get('count')}")
    bad += 0 if ok3 else 1
    return bad


def apply() -> int:
    geo = json.loads(GEOJSON.read_text(encoding="utf-8"))
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    for zid, props in TARGETS.items():
        feat = next((f for f in geo["features"] if f["properties"].get("id") == zid), None)
        entry = _entry(src, zid)
        if not feat:
            print("[실패] geojson에 구역 없음:", zid)
            return 1
        if not entry:
            print("[실패] seoul-zones.json에 구역 없음:", zid)
            return 1
        for target in (feat["properties"], entry):
            target.update({k: v for k, v in props.items() if v is not None})
            for k, v in props.items():
                if v is None:
                    target.pop(k, None)
        print(f"[갱신] {zid} {feat['properties'].get('name')} — stage={props['stage']} area={props['area']} "
              f"type={feat['properties'].get('type')}")
    geo["metadata"][META_KEY] = META
    GEOJSON.write_text(json.dumps(geo, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    SOURCE.write_text(json.dumps(src, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("[저장]", GEOJSON.relative_to(ROOT), "+", SOURCE.relative_to(ROOT))
    return 0


